"""
sisyphus.results — regenerate RESULTS.md from the code, so the document can never drift
from the measurement (the V2 README and RESULTS disagreed by a few hundred tokens/night
because hash() seeding differed per process; V3 seeds stably and writes the file itself).

    python -m sisyphus.results            # rewrites sisyphus/RESULTS.md (~3 minutes)
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

from .engine_sim import (
    NOTE, batch_table, compute_sensitivity_table, scenario_table, sensitivity_table,
)
from .geometry import (
    CPU_TFLOPS_EFF, DEFAULT_DECODE_TOKENS, DEFAULT_PROMPT_TOKENS, DRAM_GBPS, EXPERT_MB,
    GFLOP_PER_TOKEN, GPU_TFLOPS_EFF, KV_MB_PER_TOKEN, MODEL_GB, OS_RESERVE_GB, PCIE_X16_GBPS,
    TRUNK_GB, hot_set_gb,
)
from .schedule import night_comparison
from .tape import tape_table

HEADER = """# Sisyphus scheduler — measured results (V4)

Generated by `python -m sisyphus.results`. Every byte count comes from the real
`ResidencyCache` + `ExpertMajorScheduler` running real `Call` objects; throughput and
tokens/night are derived from those bytes with the stated machine envelope. Nothing here
is hand-edited.

## Envelope (geometry.py)

| quantity | value | status |
|---|---|---|
| model on disk (trunk + experts, Q2) | {model:.0f} GB | measured off the download |
| trunk pinned in RAM | {trunk:.0f} GB | measured |
| expert | {expert} MB | measured |
| hot set at hot_frac 0.10 / 0.15 | {hs10:.0f} / {hs15:.0f} GB | depends on the bracketed skew |
| KV per context token (MLA latent, fp16) | {kv:.2f} MB | estimate from latent dim |
| OS reserve | {osr:.0f} GB | assumption |
| work per token | {gf:.0f} GFLOP (92 experts / 116 trunk) | from parameter count |
| CPU effective / DRAM | {cpu} TFLOPS / {dram:.0f} GB/s | BRACKETED — Phase 0 measures |
| GPU effective / PCIe x16 | {gpu:.0f} TFLOPS / {pcie:.0f} GB/s | BRACKETED |
| job shape | {pt} prompt + {dt} decode tokens | assumption |

**Expert cache = RAM − trunk − OS − KV.** The V2 tables gave a 128 GB machine a 100 GB
expert cache; with the trunk resident that machine has about 46 GB. The tables below use
the derived budget. With a GPU holding the trunk the RAM budget recovers those 60 GB.

**Compute is a model, not a constant (V4).** Each step's wall is the slowest of SSD,
memory/PCIe traversal and FLOPs. `cpu` = experts and trunk on the cores; `gpu-trunk` =
attention/shared/dense in VRAM; `gpu-x16` / `gpu-x8` = experts streamed through the GPU
over PCIe each step, trunk in VRAM. The `bound` column names what is binding.

"""


def main(out: Path) -> None:
    t0 = time.time()
    parts = [
        HEADER.format(model=MODEL_GB, trunk=TRUNK_GB, expert=EXPERT_MB, hs10=hot_set_gb(0.10),
                      hs15=hot_set_gb(0.15), kv=KV_MB_PER_TOKEN, osr=OS_RESERVE_GB,
                      gf=GFLOP_PER_TOKEN, cpu=CPU_TFLOPS_EFF, dram=DRAM_GBPS, gpu=GPU_TFLOPS_EFF,
                      pcie=PCIE_X16_GBPS, pt=DEFAULT_PROMPT_TOKENS, dt=DEFAULT_DECODE_TOKENS),
        "## Scenarios\n\n```\n" + scenario_table() + "\n```\n",
        "## Tape regime (the assumption-free floor)\n\n```\n" + tape_table() + "\n```\n",
        "## Sensitivity — routing unknowns\n\n```\n" + sensitivity_table() + "\n```\n",
        "## Sensitivity — compute unknowns\n\n```\n" + compute_sensitivity_table() + "\n```\n",
        "## Batch curve (also the deferral curve)\n\n```\n" + batch_table() + "\n```\n",
        "## Night pipeline (mixed domains, one shared cache)\n\n```\n" + night_comparison() + "\n```\n",
        "## Notes\n\n" + NOTE + "\n",
    ]
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out} in {time.time() - t0:.0f}s", file=sys.stderr)


if __name__ == "__main__":
    main(Path(__file__).with_name("RESULTS.md"))
